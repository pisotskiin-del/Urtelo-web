def tab(key):
    for k, title, groups in TABS:
        if k == key:
            return k, title, groups
    return TABS[0]


def editable_fields(tab_key):
    """Поля potreb, которые меняются на странице правки вкладки (с шапкой)."""
    _, _, groups = tab(tab_key)
    items = HEADER + [f for _, fields in groups for f in fields]
    names = []
    for f in items:
        if not f.ro and not f.related and f.name not in names:
            names.append(f.name)
    return names
